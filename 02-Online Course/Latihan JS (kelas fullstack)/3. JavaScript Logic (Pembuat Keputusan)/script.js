// 1. Operator Pembanding
console.log(1 > 3);
console.log(1 < 3);
console.log(-1 > 1);
console.log(-1 > -1);
console.log(-1 <= -1);
console.log(-1 >= -1);

console.log("a" > "A");

let age = 21;

console.log(age > 6);
console.log(age > 25);

// 2. Kejanggalan ==
console.log(5 == 5);
console.log("b" == "c");
console.log(7 == "7");
console.log(0 == "");
console.log(true == false);
console.log(0 == false);
console.log(null == undefined);

// tips
console.log(5 === 5);
console.log(1 === 2);
console.log(7 === "7");
console.log(0 === false);

console.log(10 != "10");
console.log(10 !== "10");
